import 'package:google_generative_ai/google_generative_ai.dart';

class ChatMessage {
  final String text;
  final bool isUser;
  final DateTime timestamp;

  ChatMessage({
    required this.text,
    required this.isUser,
    required this.timestamp,
  });
}

/// Context from the CAREX application that can be supplied to the AI.
class CAREXContext {
  final String? healthCondition;
  final String? currentExercise;
  final int? targetReps;
  final int? completedReps;
  final int? targetSets;
  final int? completedSets;
  final double? formScore;
  final String? mood;
  final String? recommendedIntensity;
  final double? overallProgress;
  final int? currentHeartRate;
  final int? currentSpO2;

  const CAREXContext({
    this.healthCondition,
    this.currentExercise,
    this.targetReps,
    this.completedReps,
    this.targetSets,
    this.completedSets,
    this.formScore,
    this.mood,
    this.recommendedIntensity,
    this.overallProgress,
    this.currentHeartRate,
    this.currentSpO2,
  });

  String toPromptContext() {
    final buffer = StringBuffer();

    buffer.writeln('CAREX PATIENT CONTEXT:');

    if (healthCondition != null) {
      buffer.writeln('- Health condition: $healthCondition');
    }

    if (currentExercise != null) {
      buffer.writeln('- Current exercise: $currentExercise');
    }

    if (targetReps != null) {
      buffer.writeln('- Target repetitions: $targetReps');
    }

    if (completedReps != null) {
      buffer.writeln('- Completed repetitions: $completedReps');
    }

    if (targetSets != null) {
      buffer.writeln('- Target sets: $targetSets');
    }

    if (completedSets != null) {
      buffer.writeln('- Completed sets: $completedSets');
    }

    if (formScore != null) {
      buffer.writeln(
        '- Latest form score: ${formScore!.toStringAsFixed(0)}%',
      );
    }

    if (mood != null) {
      buffer.writeln('- Current mood/readiness state: $mood');
    }

    if (recommendedIntensity != null) {
      buffer.writeln(
        '- Recommended exercise intensity: $recommendedIntensity',
      );
    }

    if (overallProgress != null) {
      buffer.writeln(
        '- Overall rehabilitation progress: '
        '${overallProgress!.toStringAsFixed(0)}%',
      );
    }

    if (currentHeartRate != null) {
      buffer.writeln('- Current heart rate: $currentHeartRate BPM');
    }

    if (currentSpO2 != null) {
      buffer.writeln('- Current SpO2: $currentSpO2%');
    }

    return buffer.toString();
  }
}

class AIAssistantService {
  static const String _geminiApiKey = String.fromEnvironment(
    'GEMINI_API_KEY',
    defaultValue: '',
  );

  GenerativeModel? _geminiModel;

  final List<ChatMessage> _conversation = [];

  AIAssistantService() {
    if (_geminiApiKey.isNotEmpty) {
      _geminiModel = GenerativeModel(
        model: 'gemini-1.5-flash',
        apiKey: _geminiApiKey,
        systemInstruction: Content.system(
          '''
You are CAREX AI, the rehabilitation assistant inside the CAREX
(Comprehensive Adaptive Rehabilitation Expert) application.

Your role is to provide supportive, practical rehabilitation guidance
based on the information available from the CAREX application.

CORE RESPONSIBILITIES:

1. Exercise guidance
- Explain how to perform rehabilitation exercises.
- Explain the purpose of an exercise in simple language.
- Explain repetitions, sets and duration when those values are available.
- Encourage controlled and comfortable movements.

2. Posture and form guidance
- Explain posture feedback generated by CAREX.
- Help users understand why an exercise repetition may not have been counted.
- Give simple technique corrections.

3. Progress guidance
- Explain completed repetitions, sets, form scores and rehabilitation
  progress when those values are provided.
- Help the patient understand trends without making unsupported claims.

4. Patient readiness
- Explain the meaning of the current mood/readiness assessment.
- Explain the recommended exercise intensity when provided.

5. CAREX application assistance
- Explain how the exercise camera works.
- Explain repetition tracking.
- Explain progress tracking.
- Explain health/vital information displayed by CAREX.

MEDICAL SAFETY:

- You are a rehabilitation support assistant, not a doctor.
- Do not diagnose medical conditions.
- Do not prescribe or change medication.
- Do not tell the patient to stop prescribed treatment.
- Do not override instructions from a doctor or physiotherapist.
- Do not invent patient data.
- Only use patient information explicitly provided in the context.
- If information is unavailable, say that it is unavailable.
- For severe, sudden, or concerning symptoms, advise the user to seek
  appropriate medical attention.

RESPONSE STYLE:

- Be concise and conversational.
- Prefer short paragraphs and bullet points.
- Give practical steps.
- Avoid unnecessary technical terminology.
- Do not repeatedly say that you are an AI.
- Do not claim that an exercise is medically appropriate unless the
  available patient context supports that conclusion.
- If the question is unrelated to rehabilitation or CAREX, politely
  explain that you are focused on rehabilitation support.

IMPORTANT:
The patient context is data supplied by the CAREX application.
Never invent missing values.
''',
        ),
      );
    }
  }

  /// Main AI response method.
  Future<String> getResponse(
    String userQuery, {
    String? healthCondition,
    CAREXContext? carexContext,
  }) async {
    final cleanedQuery = userQuery.trim();

    if (cleanedQuery.isEmpty) {
      return 'Please enter a question and I will help you.';
    }

    final context = carexContext ??
        CAREXContext(
          healthCondition: healthCondition,
        );

    // Save user message.
    _conversation.add(
      ChatMessage(
        text: cleanedQuery,
        isUser: true,
        timestamp: DateTime.now(),
      ),
    );

    if (_geminiModel != null) {
      try {
        final response = await _generateGeminiResponse(
          cleanedQuery,
          context,
        );

        if (response != null && response.trim().isNotEmpty) {
          _conversation.add(
            ChatMessage(
              text: response.trim(),
              isUser: false,
              timestamp: DateTime.now(),
            ),
          );

          return response.trim();
        }
      } catch (e) {
        // Fall through to local CAREX response engine.
        print('CAREX AI error: $e');
      }
    }

    final fallback = _getLocalResponse(
      cleanedQuery,
      context,
    );

    _conversation.add(
      ChatMessage(
        text: fallback,
        isUser: false,
        timestamp: DateTime.now(),
      ),
    );

    return fallback;
  }

  Future<String?> _generateGeminiResponse(
    String userQuery,
    CAREXContext context,
  ) async {
    final contents = <Content>[];

    // Keep only recent conversation to prevent the prompt becoming huge.
    final recentMessages = _conversation.length > 10
        ? _conversation.sublist(_conversation.length - 10)
        : _conversation;

    for (final message in recentMessages) {
      if (message.isUser) {
        contents.add(
          Content.text(
            'USER: ${message.text}',
          ),
        );
      } else {
        contents.add(
          Content.text(
            'CAREX AI: ${message.text}',
          ),
        );
      }
    }

    contents.add(
      Content.text(
        '''
${context.toPromptContext()}

CURRENT USER QUESTION:
$userQuery

Answer the user's question using the CAREX context above.
Do not invent missing patient information.
''',
      ),
    );

    final response = await _geminiModel!.generateContent(
      contents,
    );

    return response.text;
  }

  /// Local fallback when Gemini is unavailable.
  String _getLocalResponse(
    String query,
    CAREXContext context,
  ) {
    final q = query.toLowerCase();

    // ------------------------------------------------------------
    // PROGRESS
    // ------------------------------------------------------------

    if (q.contains('progress') ||
        q.contains('improving') ||
        q.contains('recovery')) {
      if (context.overallProgress != null) {
        return '''
Your current CAREX rehabilitation progress is
${context.overallProgress!.toStringAsFixed(0)}%.

Keep completing your assigned rehabilitation sessions consistently.
Your progress should be interpreted together with exercise completion,
form quality and your clinical plan.
''';
      }

      return '''
I can help explain your rehabilitation progress.

Your current overall progress value is not available to me right now.
Check the CAREX Progress dashboard for your latest recorded activity.
''';
    }

    // ------------------------------------------------------------
    // CURRENT EXERCISE
    // ------------------------------------------------------------

    if (q.contains('rep') ||
        q.contains('repetition') ||
        q.contains('count')) {
      if (context.currentExercise != null &&
          context.completedReps != null &&
          context.targetReps != null) {
        return '''
For ${context.currentExercise}, CAREX has detected
${context.completedReps} of ${context.targetReps} target repetitions.

Try to:
• Perform the movement slowly.
• Complete the full movement range.
• Return to the starting position between repetitions.
• Keep your body position stable.

If CAREX does not detect a repetition, avoid forcing the movement.
''';
      }

      return '''
If CAREX is not counting a repetition, try performing the movement
more slowly and return fully to the starting position before beginning
the next repetition.
''';
    }

    // ------------------------------------------------------------
    // FORM
    // ------------------------------------------------------------

    if (q.contains('form') ||
        q.contains('posture') ||
        q.contains('technique')) {
      if (context.formScore != null) {
        return '''
Your latest recorded form score is
${context.formScore!.toStringAsFixed(0)}%.

Focus on controlled movement and maintaining the posture requested
for the exercise.
''';
      }

      return '''
Focus on controlled movement, stable posture and completing the
movement within a comfortable range.
''';
    }

    // ------------------------------------------------------------
    // NECK
    // ------------------------------------------------------------

    if (q.contains('neck') || q.contains('stiff')) {
      return '''
For gentle neck rehabilitation:

• Move slowly and avoid forcing the range of motion.
• Keep your shoulders relaxed.
• Return to the neutral position between movements.
• Stop if the movement causes significant or worsening pain.

CAREX exercises such as Neck Rotation and Chin Tucks can provide
guided movement tracking when available in your exercise plan.
''';
    }

    // ------------------------------------------------------------
    // SHOULDER
    // ------------------------------------------------------------

    if (q.contains('shoulder')) {
      return '''
For shoulder rehabilitation:

• Keep movements controlled.
• Avoid sudden jerking.
• Keep your posture stable.
• Follow the repetitions or duration assigned by your rehabilitation plan.

CAREX can provide movement tracking during supported shoulder exercises.
''';
    }

    // ------------------------------------------------------------
    // KNEE
    // ------------------------------------------------------------

    if (q.contains('knee')) {
      return '''
For knee rehabilitation:

• Keep the movement controlled.
• Avoid sudden loading or jerking.
• Maintain alignment during the exercise.
• Follow the exercise range and repetitions in your rehabilitation plan.

If you experience significant or worsening pain, consult your healthcare
professional.
''';
    }

    // ------------------------------------------------------------
    // BACK
    // ------------------------------------------------------------

    if (q.contains('back') ||
        q.contains('spine') ||
        q.contains('slouch')) {
      return '''
For back and posture exercises:

• Keep your spine controlled throughout the movement.
• Avoid sudden twisting.
• Maintain comfortable movement.
• Take regular posture breaks if you spend long periods sitting.
''';
    }

    // ------------------------------------------------------------
    // WRIST
    // ------------------------------------------------------------

    if (q.contains('wrist') ||
        q.contains('typing') ||
        q.contains('mouse')) {
      return '''
For wrist comfort:

• Keep your wrists in a neutral position while typing.
• Avoid prolonged extreme wrist bending.
• Take regular short breaks.
• Perform gentle wrist movements without forcing the range.
''';
    }

    // ------------------------------------------------------------
    // READINESS / MOOD
    // ------------------------------------------------------------

    if (q.contains('mood') ||
        q.contains('ready') ||
        q.contains('intensity')) {
      final intensity = context.recommendedIntensity;

      if (intensity != null) {
        return '''
CAREX currently recommends a $intensity exercise intensity
based on the available readiness assessment.

Use this recommendation together with your prescribed rehabilitation
plan and healthcare professional's instructions.
''';
      }

      return '''
Your CAREX readiness assessment helps determine the recommended
exercise intensity. The current recommendation is not available
to me right now.
''';
    }

    // ------------------------------------------------------------
    // HEALTH
    // ------------------------------------------------------------

    if (q.contains('heart rate') ||
        q.contains('heartbeat') ||
        q.contains('spo2') ||
        q.contains('oxygen')) {
      final heartRate = context.currentHeartRate;
      final spO2 = context.currentSpO2;

      final buffer = StringBuffer();

      if (heartRate != null) {
        buffer.writeln(
          'Current heart rate recorded by CAREX: $heartRate BPM.',
        );
      }

      if (spO2 != null) {
        buffer.writeln(
          'Current SpO₂ recorded by CAREX: $spO2%.',
        );
      }

      if (heartRate == null && spO2 == null) {
        return '''
Current health-vital values are not available to the assistant.
Please check the Health section of CAREX.
''';
      }

      return '''
${buffer.toString()}

These values should be interpreted in the context of your health
condition and healthcare professional's advice.
''';
    }

    return '''
I'm CAREX AI, your rehabilitation assistant.

I can help you with:

• Exercise instructions
• Repetition and form feedback
• Posture guidance
• Rehabilitation progress
• Exercise intensity
• Readiness/mood assessment
• Heart rate and SpO₂ information
• Using CAREX's rehabilitation features

Try asking:
"Why wasn't my rep counted?"
"How is my progress?"
"How should I perform this exercise?"
"Why is my form score low?"
''';
  }

  /// Clears the current conversation.
  void clearConversation() {
    _conversation.clear();
  }

  /// Returns a copy of the current conversation.
  List<ChatMessage> get conversation =>
      List.unmodifiable(_conversation);
}